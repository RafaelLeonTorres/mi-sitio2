import { describe, expect, it } from 'vitest';
import { codeMask, lineAt, splitStatements, statementCount, translate } from './translate';

const lines = (text: string) => text.split('\n').length;

describe('codeMask', () => {
  it('deja en blanco cadenas, identificadores entre comillas y comentarios, con sus saltos de línea', () => {
    const source = 'SELECT \'a;b\' AS "x;y" -- c;d\n/* e /* f */ g; */ FROM t;';
    const mask = codeMask(source);
    expect(mask).toHaveLength(source.length);
    expect(mask.split(';')).toHaveLength(2);
    expect(mask.indexOf('\n')).toBe(source.indexOf('\n'));
    expect(mask.startsWith('SELECT \'   \' AS "   "')).toBe(true);
  });

  it('entiende las comillas dobladas dentro de una cadena', () => {
    expect(codeMask("'it''s'")).toBe("'     '");
  });
});

describe('lineAt', () => {
  it('cuenta los renglones desde 1', () => {
    expect(lineAt('a\nb\nc', 0)).toBe(1);
    expect(lineAt('a\nb\nc', 2)).toBe(2);
    expect(lineAt('a\nb\nc', 4)).toBe(3);
  });
});

describe('translate', () => {
  it('pasa [Nombre] a "nombre" sin tocar las cadenas', () => {
    const result = translate("SELECT [OrderDate], '[x]' FROM [Orders];");
    expect(result.sql).toBe('SELECT "orderdate", \'[x]\' FROM "orders";');
    expect(result.notes).toContain('brackets');
  });

  it('quita los GO sin mover los renglones', () => {
    const source = 'SELECT 1;\nGO\nSELECT 2;';
    const result = translate(source);
    expect(lines(result.sql)).toBe(lines(source));
    expect(result.sql).not.toContain('GO');
    expect(result.notes).toEqual(['go']);
  });

  it('pone entre comillas la parte de fecha de DATEADD, DATEDIFF, DATEPART y DATETRUNC', () => {
    const result = translate(
      'SELECT DATEADD(day, 1, d), DATEDIFF (month, a, b), DATEPART(dw, d), DATETRUNC(year, d);',
    );
    expect(result.sql).toBe(
      "SELECT DATEADD('day', 1, d), DATEDIFF ('month', a, b), DATEPART('dw', d), DATETRUNC('year', d);",
    );
  });

  it('cambia los tipos de SQL Server y quita NONCLUSTERED', () => {
    const result = translate(
      'CREATE TABLE t (a nvarchar(20), b datetime2, c bit, d nvarchar(max), e money);\nCREATE NONCLUSTERED INDEX ix ON t (a);',
    );
    expect(result.sql).toContain(
      'a varchar(20), b timestamp, c smallint, d text, e numeric(19, 4)',
    );
    expect(result.sql).toContain('CREATE INDEX ix ON t (a);');
    expect(result.notes).toContain('types');
    expect(result.notes).toContain('nonclustered');
  });

  it('traduce TRAN, IDENTITY y las pistas de tabla', () => {
    const source =
      'BEGIN TRAN;\nCREATE TABLE t (Id int IDENTITY(1, 1));\nSELECT * FROM t\nWITH (NOLOCK)\nWHERE Id = 1;\nCOMMIT TRAN;';
    const result = translate(source);
    expect(result.sql).toContain('BEGIN TRANSACTION;');
    expect(result.sql).toContain('COMMIT TRANSACTION;');
    expect(result.sql).toContain('Id int GENERATED BY DEFAULT AS IDENTITY');
    expect(result.sql).not.toContain('NOLOCK');
    expect(lines(result.sql)).toBe(lines(source));
  });

  it('mueve el ORDER BY de WITHIN GROUP dentro de STRING_AGG', () => {
    const result = translate("SELECT STRING_AGG(Name, ', ') WITHIN GROUP (ORDER BY Name) FROM t;");
    expect(result.sql).toBe("SELECT STRING_AGG(Name, ', ' ORDER BY Name) FROM t;");
  });

  it('traduce CONVERT de dos argumentos y bloquea el de estilo', () => {
    expect(
      translate('SELECT CONVERT(date, OrderDate), CONVERT(nvarchar(10), Total) FROM t;').sql,
    ).toBe('SELECT CAST(OrderDate AS date), CAST(Total AS varchar(10)) FROM t;');
    expect(translate('SELECT CONVERT(varchar(10), d, 120) FROM t;').blocked).toEqual([
      { key: 'convert-style', line: 1 },
    ]);
  });

  it('traduce CROSS APPLY y OUTER APPLY', () => {
    expect(translate('SELECT * FROM a CROSS APPLY (SELECT 1 AS x) AS b;').sql).toBe(
      'SELECT * FROM a CROSS JOIN LATERAL (SELECT 1 AS x) AS b;',
    );
    expect(translate('SELECT * FROM a OUTER APPLY (SELECT 1 AS x) AS b WHERE 1 = 1;').sql).toBe(
      'SELECT * FROM a LEFT JOIN LATERAL (SELECT 1 AS x) AS b ON TRUE WHERE 1 = 1;',
    );
  });

  it('quita SET NOCOUNT y SET XACT_ABORT, y el alias de las columnas del SET', () => {
    const result = translate(
      'SET NOCOUNT ON;\nSET XACT_ABORT ON;\nUPDATE p SET p.Price = 1 WHERE p.Id = 2;',
    );
    expect(result.sql).toBe('\n\nUPDATE p SET Price = 1 WHERE p.Id = 2;');
    expect(result.notes).toContain('set-option');
    expect(result.notes).toContain('set-alias');
  });

  it('cambia BY TARGET de MERGE y las tablas temporales', () => {
    const result = translate(
      'MERGE INTO t USING s ON t.a = s.a WHEN NOT MATCHED BY TARGET THEN INSERT (a) VALUES (s.a);\nSELECT * INTO #Tmp FROM t;',
    );
    expect(result.sql).toContain('WHEN NOT MATCHED THEN');
    expect(result.sql).toContain('INTO "#tmp"');
  });

  it('bloquea lo que PostgreSQL no puede correr y dice el renglón', () => {
    const cases: [string, string, number][] = [
      ['SELECT 1;\nSELECT TOP 5 * FROM t;', 'top', 2],
      ['DECLARE @x int = 1;', 'variable', 1],
      ['BEGIN TRY\nSELECT 1;\nEND TRY', 'try-catch', 1],
      ['EXEC dbo.Report;', 'procedure', 1],
      ['IF 1 = 1 SELECT 1;', 'control-flow', 1],
      ['DELETE FROM t OUTPUT DELETED.* WHERE a = 1;', 'output', 1],
      ["PRINT 'hola';", 'print', 1],
      [
        'UPDATE p SET Price = 1 FROM Products AS p JOIN Categories AS c ON c.Id = p.CategoryId;',
        'update-join',
        1,
      ],
      [
        'DELETE l FROM OrderLines AS l LEFT JOIN Orders AS o ON o.Id = l.OrderId;',
        'delete-join',
        1,
      ],
      [';WITH d AS (SELECT Id FROM Customers)\nDELETE FROM d;', 'cte-target', 2],
    ];
    for (const [source, key, line] of cases) {
      expect(translate(source).blocked, source).toEqual([{ key, line }]);
    }
  });

  it('no bloquea las formas que sí corren en los dos motores', () => {
    for (const source of [
      "SELECT 'TOP 5', '@x', IIF(1 = 1, 'IF', 'WHILE') FROM t;",
      'UPDATE Products SET Price = 1 FROM Categories AS c WHERE c.Id = Products.CategoryId;',
      'UPDATE Customers SET City = 1 WHERE Id IN (SELECT Id FROM Customers WHERE City = 2);',
      'WITH d AS (SELECT Id FROM Customers) DELETE FROM Customers WHERE Id IN (SELECT Id FROM d);',
      'DELETE FROM OrderLines WHERE NOT EXISTS (SELECT 1 FROM Orders AS o WHERE o.Id = OrderLines.OrderId);',
    ]) {
      expect(translate(source).blocked, source).toEqual([]);
    }
  });
});

describe('splitStatements', () => {
  it('parte en cada punto y coma fuera de cadenas y comentarios, sin sentencias vacías', () => {
    const source = "SELECT ';';\n-- nada;\n;SELECT 2 /* ; */;\n";
    const statements = splitStatements(source);
    expect(statements.map((statement) => statement.text.trim())).toEqual([
      "SELECT ';';",
      'SELECT 2 /* ; */;',
    ]);
    expect(statements[1]?.start).toBe(source.indexOf('SELECT 2'));
    expect(statementCount(source)).toBe(2);
    expect(statementCount('  -- solo un comentario\n')).toBe(0);
  });

  it('acepta una última sentencia sin punto y coma', () => {
    expect(splitStatements('SELECT 1; SELECT 2').map((statement) => statement.text.trim())).toEqual(
      ['SELECT 1;', 'SELECT 2'],
    );
  });
});
